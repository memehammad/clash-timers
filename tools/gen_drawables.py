#!/usr/bin/env python3
"""Generates the expressive shapes and animated wave drawables into app/src/main/res/drawable.

Run from the project root:  python3 tools/gen_drawables.py
"""
import math
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_drawables.py -->\n'


def polar_shape(lobes, depth, size=48.0, steps=192, base=None):
    """Closed path of a rounded 'lobed' shape (cookie, clover, flower...) in a size x size box."""
    r = size / 2
    pts = []
    for i in range(steps):
        a = 2 * math.pi * i / steps
        rr = r * ((1 - depth) + depth * math.cos(lobes * a)) if base is None else r * base(a)
        pts.append((r + rr * math.cos(a - math.pi / 2), r + rr * math.sin(a - math.pi / 2)))
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"


def vector(path, color, size=48):
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp" android:height="{size}dp"\n'
        f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n'
        f'    <path android:fillColor="@color/{color}" android:pathData="{path}" />\n'
        "</vector>\n"
    )


def write(name, text):
    with open(os.path.join(OUT, name + ".xml"), "w") as f:
        f.write(text)


# --- Section shapes (Material 3 Expressive shape set) -----------------------------------
SHAPES = {
    "shape_cookie": (polar_shape(9, 0.07), "w_c1"),          # Builders
    "shape_clover": (polar_shape(4, 0.16), "w_c3"),          # Laboratory
    "shape_flower": (polar_shape(6, 0.12), "w_c2"),          # Pet House
    "shape_sunny": (polar_shape(8, 0.05), "w_c2"),           # Builder Base
    "shape_circle": (polar_shape(1, 0.0), "w_cn"),           # Helpers / other
}
for name, (path, color) in SHAPES.items():
    write(name, vector(path, color))

# --- Builder badge: busy (static) and free (slowly spinning AVD) ------------------------
cookie = polar_shape(9, 0.07)
write("cookie_busy", vector(cookie, "w_badge_busy"))
write("cookie_free", vector(cookie, "w_badge_free"))
write(
    "cookie_spin",
    HEADER
    + '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    xmlns:aapt="http://schemas.android.com/aapt">\n'
    '    <aapt:attr name="android:drawable">\n'
    '        <vector android:width="48dp" android:height="48dp"\n'
    '            android:viewportWidth="48" android:viewportHeight="48">\n'
    '            <group android:name="spin" android:pivotX="24" android:pivotY="24">\n'
    f'                <path android:fillColor="@color/w_badge_free" android:pathData="{cookie}" />\n'
    "            </group>\n"
    "        </vector>\n"
    "    </aapt:attr>\n"
    '    <target android:name="spin">\n'
    '        <aapt:attr name="android:animation">\n'
    '            <objectAnimator android:propertyName="rotation" android:valueFrom="0" android:valueTo="360"\n'
    '                android:valueType="floatType" android:duration="24000" android:repeatCount="infinite"\n'
    '                android:interpolator="@android:anim/linear_interpolator" />\n'
    "        </aapt:attr>\n"
    "    </target>\n"
    "</animated-vector>\n",
)

# --- Squiggly progress (like the media player): a thin sine wave that keeps moving -------
W, H = 240, 12          # viewport
WAVELENGTH = 20.0
AMPLITUDE = 2.6
STROKE = 2.4
pts = []
x = -WAVELENGTH
while x <= W + WAVELENGTH + 0.01:
    pts.append((x, H / 2 + AMPLITUDE * math.sin(2 * math.pi * x / WAVELENGTH)))
    x += 1.0
wave = "M" + " L".join(f"{px:.1f},{py:.2f}" for px, py in pts)
write(
    "wave_anim",
    HEADER
    + '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    xmlns:aapt="http://schemas.android.com/aapt">\n'
    '    <aapt:attr name="android:drawable">\n'
    f'        <vector android:width="{W}dp" android:height="{H}dp"\n'
    f'            android:viewportWidth="{W}" android:viewportHeight="{H}">\n'
    '            <group android:name="wave">\n'
    f'                <path android:pathData="{wave}" android:strokeColor="@color/w_accent"\n'
    f'                    android:strokeWidth="{STROKE}" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
    "            </group>\n"
    "        </vector>\n"
    "    </aapt:attr>\n"
    '    <target android:name="wave">\n'
    '        <aapt:attr name="android:animation">\n'
    f'            <objectAnimator android:propertyName="translateX" android:valueFrom="0" android:valueTo="{WAVELENGTH}"\n'
    '                android:valueType="floatType" android:duration="1100" android:repeatCount="infinite"\n'
    '                android:interpolator="@android:anim/linear_interpolator" />\n'
    "        </aapt:attr>\n"
    "    </target>\n"
    "</animated-vector>\n",
)
write(
    "wave_track",
    HEADER
    + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    f'    android:width="{W}dp" android:height="{H}dp"\n'
    f'    android:viewportWidth="{W}" android:viewportHeight="{H}">\n'
    f'    <path android:pathData="M2,{H / 2} L{W - 2},{H / 2}" android:strokeColor="@color/w_track"\n'
    f'        android:strokeWidth="{STROKE}" android:strokeLineCap="round" />\n'
    "</vector>\n",
)
print("ok")
